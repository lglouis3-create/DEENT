/* ==========================================================================
   "SEE IT ON THE STRUCTURE", PHAR 4346 DEENT: presentation
   --------------------------------------------------------------------------
   Course-level presentation (Louis, 2026-11-08: "An explanation like this
   isn't helping in learning how to distinguish the alpha hydroxy acids as it
   doesn't explain this visually"). Temporary until the kit has explanation
   figures. The kit core is not changed and nothing is stored.
   For a question listed in EXFIG_DATA.byQ (exfig.js, generated by
   gen_exfig.py from exfig_data.json and the Atlas SMILES), an annotated
   drawing of the molecule(s), marked on the atoms the explanation names,
   goes into "The concept behind this" under the heading "See it on the
   structure". Only once the question is answered: the explanation block
   (.teach) is drawn by the core only after an answer (the drill, the
   All-on-one-page cards of topic_list_ui.js, a finished paper's review), and
   this file adds the figure only inside such a block, never on a running
   exam paper (Q.examMode / an unsubmitted EX). The figure scrolls sideways
   inside its own box on a phone and has Enlarge (the core's figBig, through
   the core's [data-anim] button handler), as the Guide's figures do.
   How: a MutationObserver on #v-quiz and #v-exam (so it follows every way
   those panes are redrawn, including the All-on-one-page cards refreshed one
   at a time), and an idempotent pass right after renderQuiz() and
   renderExamResult().
   API: EXFIG.get(qid) gives the figure's HTML (or ''), EXFIG.has(qid), for
   other course files ("Hear the why" may show the same figure).
   In the node checks' stub DOM it draws nothing.
   ========================================================================== */
const EXFIG = (() => {
  const D = (typeof EXFIG_DATA !== 'undefined' && EXFIG_DATA) || {figs: {}, byQ: {}};
  const figOf = id => (D.byQ[id] && D.figs[D.byQ[id]]) || null;
  const has = id => !!figOf(id);
  const e = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
  const get = id => {
    const f = figOf(id); if (!f) return '';
    return `<figure class="fig exfig" data-xf="${e(D.byQ[id])}"><div class="xfscroll" tabindex="0" role="group" aria-label="${e(f.title)}">${f.svg}</div>` +
      `<figcaption><b>${e(f.title)}.</b> ${e(f.caption)}</figcaption>` +
      `<div class="anim xfctl" data-anim="xf-${e(D.byQ[id])}"><button type="button" class="btn ghost" data-go="big" aria-pressed="false">Enlarge</button></div></figure>`;
  };
  const block = id => `<div class="xfwrap" data-xfq="${e(id)}"><h5 class="tsec">See it on the structure</h5>${get(id)}</div>`;
  const css = `
/* the site has no dark theme yet: the drawing follows the page's own --text and --paper
   (bonds currentColor), so it turns with the page when one comes */
:root{--xf-key:rgba(0,114,178,.26);--xf-key-line:#0072B2;--xf-acid:rgba(230,159,0,.34);--xf-acid-line:#9A6700;
  --xf-diff:rgba(204,121,167,.34);--xf-diff-line:#A0507E}
.xfwrap{margin:12px 0 4px}
.fig.exfig{max-width:none;background:var(--paper);color:var(--text)}
.fig.exfig .xfscroll{overflow-x:auto;-webkit-overflow-scrolling:touch;overscroll-behavior-x:contain}
.fig.exfig .xfscroll:focus-visible{outline:2px solid var(--accent);outline-offset:2px}
.fig.exfig svg.xf{width:auto;max-width:none;height:auto;display:block;margin:0 auto;color:var(--text);
  font-family:system-ui,-apple-system,"Segoe UI",Roboto,sans-serif}
.fig.exfig.big svg.xf{width:100%;max-width:none;max-height:calc(100vh - 190px);max-height:calc(100dvh - 190px)}
.fig.exfig .xfctl{margin:4px 0 0}
.xf .xt{font-size:12px;font-weight:700;fill:var(--text)}
.xf .xl{font-size:11px;font-weight:600;fill:var(--text)}
.xf .xl.xp{font-size:12px;font-weight:700;paint-order:stroke;stroke:var(--paper);stroke-width:3px}
.xf .xb{fill:var(--paper);stroke-width:1.4}
.xf .xb.key{stroke:var(--xf-key-line)}
.xf .xb.acid{stroke:var(--xf-acid-line);stroke-dasharray:4 2}
.xf .xb.diff{stroke:var(--xf-diff-line);stroke-dasharray:1.5 1.5;stroke-width:1.8}
.xf .xc{fill:none;stroke:currentColor;stroke-width:1.1;stroke-dasharray:2.5 2}
.xf .xld{stroke:var(--text-dim);stroke-width:1;fill:none}
.xf .xr{font-size:15px;font-weight:700;font-style:italic;fill:var(--text-dim)}
.xf .xn{font-size:9px;fill:var(--text-dim)}
.xf .xv{font-size:11.5px;fill:var(--text)}
.xf .xv.yes{font-weight:700}
`;
  const ok = typeof document !== 'undefined' && typeof MutationObserver !== 'undefined' &&
             typeof document.getElementById === 'function' && document.getElementById('v-quiz') &&
             typeof document.getElementById('v-quiz').querySelectorAll === 'function';
  const api = {has, get, ids: () => Object.keys(D.byQ), css};
  if (!ok) return api;

  const addCss = () => {
    if (document.getElementById('xfcss')) return;
    const s = document.createElement('style'); s.id = 'xfcss'; s.textContent = css; document.head.appendChild(s);
  };
  const put = (teach, id) => {
    if (!teach || !id || !has(id)) return;
    const old = teach.querySelector(':scope > .xfwrap');
    if (old && old.dataset.xfq === id) return;
    if (old) old.remove();
    teach.insertAdjacentHTML('beforeend', block(id));
  };
  function decorate() {
    // the drill, one at a time: the explanation of the question on screen, once answered
    try {
      if (typeof Q !== 'undefined' && Q && Q.current && Q.revealed && !Q.examMode) {
        document.querySelectorAll('#v-quiz > .qcard .why > .teach').forEach(t => put(t, Q.current.id));
      }
    } catch (err) { /* the drill is not open */ }
    // All on one page (topic_list_ui.js): each answered card carries its id
    document.querySelectorAll('#v-quiz .tlcard[data-tlq] .why > .teach').forEach(t => put(t, t.closest('.tlcard').dataset.tlq));
    // a finished paper's review: card i is EX.qs[i]
    try {
      if (typeof EX !== 'undefined' && EX && Array.isArray(EX.qs) && EX.done === true) {
        const cards = [...document.querySelectorAll('#v-exam > .qcard')];
        if (cards.length === EX.qs.length) cards.forEach((c, i) => {
          const t = c.querySelector('.teach'); if (t && EX.qs[i]) put(t, EX.qs[i].id);
        });
      }
    } catch (err) { /* no paper */ }
  }
  let busy = false;
  const run = () => {
    if (busy) return; busy = true;
    try { decorate(); } catch (err) { console.error('"See it on the structure" could not be drawn; the question is unaffected.', err); }
    busy = false;
  };
  try {
    addCss();
    const mo = new MutationObserver(run);
    ['v-quiz', 'v-exam'].forEach(v => { const el = document.getElementById(v); if (el) mo.observe(el, {childList: true, subtree: true}); });
    if (typeof renderQuiz === 'function') {
      const oq = renderQuiz;
      renderQuiz = function () { const r = oq.apply(this, arguments); run(); return r; };
    }
    if (typeof renderExamResult === 'function') {
      const oe = renderExamResult;
      renderExamResult = function () { const r = oe.apply(this, arguments); run(); return r; };
    }
  } catch (err) { console.error('"See it on the structure" could not be added; the rest of the page is unaffected.', err); }
  return api;
})();
if (typeof window !== 'undefined' && window) window.EXFIG = EXFIG;
