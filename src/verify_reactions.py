#!/usr/bin/env python3
"""Verify every species of the reaction figures against PubChem and ChEMBL.

    VERIFY_CACHE=<dir> python3 -I verify_reactions.py
        writes verification/reactions_verification.json and .md

The same lookups and status rules as the Atlas (verify_pubchem.py, whose functions this
script calls): the exact InChIKey of the drawn SMILES, then the same connectivity, then
the name; ChEMBL by the id the species carries (the Atlas item's id where the species is
an Atlas structure). A species drawn with a DNA attachment atom is looked up by its
`verify_smiles` (the base itself, or N-methyl in place of the strand). Species marked
`teaching` (a radical, the drawn DNA adduct) are checked and recorded, not forced onto a
drug record. Rerun after any SMILES change in reactions_data.json.
"""
import json, os, sys, datetime
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import verify_pubchem as V
from rdkit import Chem

DATA = os.path.join(HERE, 'reactions_data.json')


def main():
    data = json.load(open(DATA))
    today = datetime.date.today().isoformat()
    res = []
    for s in data['species']:
        if s.get('teaching'):
            V.TEACHING.add(s['id'])
        it = {'key': s['id'], 'name': s['name'], 'slide': s['slide'], 'priority': None,
              'smiles': s.get('verify_smiles', s['smiles'])}
        if s.get('chembl_id'):
            it['chembl_id'] = s['chembl_id']
        r = V.verify(it)
        r['drawn_smiles'] = s['smiles']
        r['atlas_item'] = s.get('atlas')
        r['date'] = today
        res.append(r)
        print('%-14s %-19s %s' % (s['id'], r['status'], (r['pubchem'] or {}).get('cid', '')), flush=True)
    meta = {'date': today, 'sources': {'pubchem': V.PUG, 'chembl': V.CHEMBL, 'rdkit': Chem.rdBase.rdkitVersion},
            'species': len(res)}
    os.makedirs(V.OUTDIR, exist_ok=True)
    json.dump({'meta': meta, 'results': res}, open(os.path.join(V.OUTDIR, 'reactions_verification.json'), 'w'),
              indent=1, ensure_ascii=False)
    from collections import Counter
    cnt = Counter(r['status'] for r in res)
    L = ['# Reaction figures: species verification (%s)' % today, '',
         'Generated by `src/verify_reactions.py` (the Atlas\'s `verify_pubchem.py` lookups) from live PubChem PUG-REST and '
         'ChEMBL REST queries; RDKit %s computes the drawn side.' % meta['sources']['rdkit'], '',
         '| Status | Species |', '|---|---|'] + ['| %s | %d |' % kv for kv in sorted(cnt.items())] + [
         '', '| Species | Name on the slide | Deck p. | Atlas item | PubChem CID | ChEMBL | Status | Detail |',
         '|---|---|---|---|---|---|---|---|']
    for r in res:
        L.append('| %s | %s | %s | %s | %s | %s | %s | %s |' % (
            r['key'], r['name'], r['slide'], r['atlas_item'] or '', (r['pubchem'] or {}).get('cid', ''),
            (r['chembl'] or {}).get('id', ''), r['status'], r['detail'].replace('|', '/')))
    open(os.path.join(V.OUTDIR, 'reactions_verification.md'), 'w').write('\n'.join(L) + '\n')
    bad = [r['key'] for r in res if r['status'] in ('mismatch', 'not-found') or not r['pubchem_checked']]
    print('verified %d species: %s%s' % (len(res), dict(cnt), ('; PROBLEMS: %s' % bad) if bad else ''))
    sys.exit(1 if bad else 0)


if __name__ == '__main__':
    main()
